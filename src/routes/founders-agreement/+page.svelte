  <h2>1. The founders</h2>
  <p>This agreement is between <strong>Brady Krupa</strong> (CEO &amp; Founder) and <strong>Arjun Bhanderi</strong> (Co-Founder &amp; Developer), together the “Founders.” Each Founder confirms they are 18 or older and able to sign this agreement.</p>

  <h2>2. The business</h2>
  <p>The “Business” means Programs For You and everything that belongs to it or grows out of it, now and in the future, including the programsforyou.com website and domain, the Email Assistant and Screen Assistant apps, the Founders’ rights in School Schedule (shared with Owen Wang under its open-source license), all code, designs, names, logos, and brands, all online accounts and signing keys, all email lists, all money and income, and any future apps, products, websites, or companies the Founders create through it.</p>

  <h2>3. Ownership: 50% each</h2>
  <ul>
    <li><strong>Brady Krupa owns 50%</strong> of the Business.</li>
    <li><strong>Arjun Bhanderi owns 50%</strong> of the Business.</li>
    <li>Profits, losses, and anything of value the Business has are shared 50/50.</li>
    <li>Each Founder gives the Business everything they have made or will make for it, including all copyrights and other rights in their code, designs, and work. It is owned jointly by both Founders, 50% each, and is © 2026 Brady Krupa and Arjun Bhanderi.</li>
  </ul>

  <h2>4. Control: the Founders decide everything</h2>
  <p>The Founders have absolute and exclusive control over the Business, including:</p>
  <ul>
    <li><strong>The Board of Trustees:</strong> the Founders decide who is on the Board, can add or remove trustees at any time, and can approve, change, or overrule any Board decision. The Board advises the Founders and has no power without their approval.</li>
    <li><strong>Voting and power:</strong> only the Founders have votes on Business decisions. Votes or opinions from trustees, team members, employees, or interns are advice only.</li>
    <li><strong>Equity and ownership:</strong> only the Founders own the Business. No one else gets equity, shares, profits, or ownership.</li>
    <li><strong>Team and roles:</strong> the Founders choose every title and role, and can add, change, or remove them at any time.</li>
    <li><strong>Money, products, and expansion:</strong> the Founders decide what to build, what to charge, how money is spent, and how the Business grows, including new apps, products, websites, partnerships, and companies.</li>
  </ul>

  <h2>5. How the Founders decide</h2>
  <ol>
    <li>The Founders try to agree on every important decision.</li>
    <li>If they can’t agree after talking it over in good faith, <strong>Brady Krupa, as CEO, makes the final decision</strong> (the tie-breaker).</li>
    <li><strong>The tie-breaker does not apply</strong> to these decisions, which always need <strong>both</strong> Founders to agree in writing: changing either Founder’s 50% ownership; giving anyone else ownership, equity, or shares; adding a new owner or founder; selling, transferring, or shutting down the whole Business; forming a company and moving the Business into it; and changing this agreement.</li>
  </ol>

  <h2>6. Team members, trustees, and helpers</h2>
  <p>Board members, heads of departments, employees, interns, and anyone else who helps the Business get no ownership, equity, vote, profit share, or rights in its code or products, unless both Founders sign a written agreement saying otherwise. Their work for the Business belongs to the Business.</p>

  <h2>7. Growing into a company</h2>
  <p>If the Founders form a company (for example, an LLC), they will each own 50% of it, unless both agree otherwise in writing, and the company will follow this agreement’s rules on control and decisions.</p>

  <h2>8. If a Founder wants to leave</h2>
  <p>A Founder’s 50% stays theirs unless both Founders agree in writing to a change, such as a buyout. Neither Founder can sell or give away their share without the other Founder’s written consent, and the other Founder gets the first chance to buy it.</p>

  <h2>9. Keeping things safe</h2>
  <p>Both Founders keep the Business’s passwords, signing keys, code, and private plans confidential and use them only for the Business. Both Founders have a right to access the Business’s accounts and records.</p>

  <h2>10. Legal details</h2>
  <ul>
    <li>This agreement is legally binding on both Founders. It can only be changed by a written document signed (including electronically) by both Founders.</li>
    <li>Electronic signatures (for example, signing a PDF of this agreement in Preview or with an e-signature service) count the same as handwritten signatures. The Founders may sign separate copies, and together they make one agreement.</li>
    <li>It is governed by the laws of the State of Connecticut, USA.</li>
    <li>If a court finds any part can’t be enforced, that part is limited only as much as needed, and the rest stays in effect.</li>
    <li>Publishing this agreement on programsforyou.com doesn’t give anyone else any rights under it.</li>
  </ul>

